"""
Mission Layout — per-mission artifact isolation under runtime_state
====================================================================

Gives the OMNI_FORGE_SUPER_AGENT factory (and any other mission runner) a
deterministic, hash-pinned workspace that never touches governance docs.

Location contract
-----------------
    03_VAULT/runtime_state/missions/<mission_id>/
      mission.json                intent snapshot (id, objective, steps, status)
      blueprint.json              frozen schemas/types/HLD        (Step_2 artifact)
      task_dag.json               decomposed task DAG             (Step_3 artifact)
      skills_manifest.json        per-mission tool contracts      (Step_4 artifact)
      verification.json           crucible/Rigor Ladder results   (Step_5 artifact)
      receipts/                   hash-pinned step receipts (append-only naming)

Governance guard: `docs/blueprint.md`, `docs/task.md`, `docs/verification.md`,
and any `PROVENANCE_LEDGER.md` are NEVER written by this module. The factory
emits its per-mission artifacts under runtime_state; the governance docs stay
authoritative at the repo level. (AGENTS.md: governance artifacts are not
regenerated by agent flows.)

Hash pinning: every `write_artifact` returns a sha256 receipt. `verify_mission`
re-hashes each artifact and compares against the mission manifest, so any
post-hoc mutation is detectable.

Run as module:
    python -m control_plane.mission_layout --test
"""
from __future__ import annotations

__version__ = "1.0.0"

import argparse
import hashlib
import json
import re
import sys
import time
from pathlib import Path
from typing import Any

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

CAMELOT_HOME = Path(__file__).resolve().parent.parent
RUNTIME_STATE = CAMELOT_HOME / "03_VAULT" / "runtime_state"
MISSIONS_ROOT = RUNTIME_STATE / "missions"

# ---------------------------------------------------------------------------
# Governance guard
# ---------------------------------------------------------------------------

# Basenames that must NEVER be written by mission artifacts, at any depth.
GOVERNANCE_DOC_BASENAMES = frozenset(
    {
        "PROVENANCE_LEDGER.md",
        "HELIO_PATCH.json",
        "config.json",
        "omnivoice-router.js",
    }
)

# Directory names where governance docs live; never written at any depth.
GOVERNANCE_DOC_DIRS = frozenset({"docs"})

# The five canonical step artifacts a mission may own (basename: description).
MISSION_ARTIFACTS: dict[str, str] = {
    "blueprint.json": "Frozen schemas, types, and high-level design (Step_2)",
    "task_dag.json": "Decomposed task DAG for swarm squire execution (Step_3)",
    "skills_manifest.json": "Per-mission tool contracts and runtime boundaries (Step_4)",
    "verification.json": "Crucible / Rigor Ladder results (Step_5)",
    "receipts": "Append-only hash-pinned step receipts",
}

_MISSION_ID_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{2,63}$")


def is_governance_path(path: Path) -> bool:
    """True if `path` must never be written by a mission artifact writer.

    Two rules, cheapest first:
      1. Basename match — governance basenames are protected wherever they
         live, including the root and mirrored ledger copies.
      2. Ancestor match — docs/ is governance territory at any depth, so
         docs/blueprint.md, docs/task.md, docs/verification.md and friends
         are covered without enumerating them.
    """
    if path.name in GOVERNANCE_DOC_BASENAMES:
        return True
    return any(part in GOVERNANCE_DOC_DIRS for part in path.parts)


def slugify_mission_id(text: str, fallback: str = "factory-mission") -> str:
    """Turn free-form intent text into a valid mission id slug.

    Lowercase, collapse non-alphanumerics to '-', trim, cap at 64 chars.
    Falls back to `<fallback>-<date>` when nothing usable survives.
    """
    slug = re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")
    slug = slug[:64].rstrip("-")
    if not _MISSION_ID_RE.match(slug):
        slug = f"{fallback}-{time.strftime('%Y%m%d')}"
    return slug


def is_valid_mission_id(mission_id: str) -> bool:
    """True when mission_id satisfies the layout contract regex."""
    return bool(_MISSION_ID_RE.match((mission_id or "").strip()))


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


# ---------------------------------------------------------------------------
# Mission session
# ---------------------------------------------------------------------------


class MissionLayoutError(ValueError):
    """Raised when a mission operation would violate the layout contract."""


class MissionSession:
    """Scoped writer for one mission's artifact tree.

    Every write is (a) confined to the mission directory, (b) refused for
    governance paths (defense in depth — the path check runs even though the
    root is already runtime_state/missions), and (c) hash-pinned via a
    receipt. Receipts are append-only: `receipts/NN_step.json` never
    overwrites an existing step number.
    """

    def __init__(self, mission_id: str, objective: str = "", root: Path | None = None):
        mid = (mission_id or "").strip()
        if not _MISSION_ID_RE.match(mid):
            raise MissionLayoutError(
                f"invalid mission_id {mission_id!r}: must match {_MISSION_ID_RE.pattern}"
            )
        self.mission_id = mid
        self.objective = objective
        self.root = (root or (MISSIONS_ROOT / mid)).resolve()
        self.manifest_path = self.root / "mission.json"
        self.receipts: list[dict[str, Any]] = []

    # -- path safety ---------------------------------------------------------

    def _safe_child(self, relative: str) -> Path:
        rel = Path(relative)
        if rel.is_absolute() or ".." in rel.parts:
            raise MissionLayoutError(f"artifact path escapes mission root: {relative!r}")
        target = (self.root / rel).resolve()
        if target != self.root and self.root not in target.parents:
            raise MissionLayoutError(f"artifact path escapes mission root: {relative!r}")
        if is_governance_path(target):
            raise MissionLayoutError(f"refusing to write governance path: {target}")
        return target

    # -- lifecycle -----------------------------------------------------------

    def create(self, steps: list[str] | None = None) -> dict[str, Any]:
        """Scaffold the mission directory and manifest. Idempotent."""
        if is_governance_path(self.root):
            raise MissionLayoutError(
                f"refusing to create mission inside governance territory: {self.root}"
            )
        self.root.mkdir(parents=True, exist_ok=True)
        (self.root / "receipts").mkdir(exist_ok=True)
        manifest = {
            "schema": "camelot.mission/1",
            "mission_id": self.mission_id,
            "objective": self.objective,
            "steps": steps
            or [
                "OBSERVE_AND_SCAFFOLD",
                "ARCHITECT_BLUEPRINT",
                "DECOMPOSE_TASK_DAG",
                "EQUIP_KNIGHTS",
                "VALIDATION_SWARM",
            ],
            "status": "OPEN",
            "artifacts": {},
            "created_at": _now(),
        }
        if self.manifest_path.exists():
            existing = json.loads(self.manifest_path.read_text(encoding="utf-8"))
            existing.setdefault("status", "OPEN")
            self.manifest_path.write_text(
                json.dumps(existing, indent=2, ensure_ascii=False), encoding="utf-8"
            )
            return existing
        self.manifest_path.write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
        )
        return manifest

    def load_manifest(self) -> dict[str, Any]:
        if not self.manifest_path.exists():
            raise MissionLayoutError(f"mission not initialized: {self.mission_id}")
        return json.loads(self.manifest_path.read_text(encoding="utf-8"))

    # -- artifact writes -----------------------------------------------------

    def write_artifact(self, name: str, payload: Any) -> dict[str, Any]:
        """Write a mission artifact + append-only receipt. Returns the receipt.

        `name` must be one of the canonical MISSION_ARTIFACTS basenames
        (or `receipts/…`), keeping the layout deterministic for the crucible.
        """
        if name not in MISSION_ARTIFACTS:
            raise MissionLayoutError(
                f"unknown artifact {name!r}; canonical set: {sorted(MISSION_ARTIFACTS)}"
            )
        target = self._safe_child(name)
        target.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
        try:
            rel_path = str(target.relative_to(CAMELOT_HOME))
        except ValueError:  # external root (e.g. test tempdir) — keep absolute
            rel_path = str(target)
        receipt = {
            "artifact": name,
            "path": rel_path,
            "sha256": _sha256_file(target),
            "bytes": target.stat().st_size,
            "written_at": _now(),
        }
        self._append_receipt(receipt)

        manifest = self.load_manifest()
        manifest.setdefault("artifacts", {})[name] = receipt["sha256"]
        self.manifest_path.write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
        )
        return receipt

    def _append_receipt(self, receipt: dict[str, Any]) -> None:
        receipts_dir = self.root / "receipts"
        n = 1
        while (receipts_dir / f"{n:03d}_step.json").exists():
            n += 1
        entry = dict(receipt)
        entry["receipt_no"] = n
        (receipts_dir / f"{n:03d}_step.json").write_text(
            json.dumps(entry, indent=2, ensure_ascii=False), encoding="utf-8"
        )
        self.receipts.append(entry)

    # -- status / verification ------------------------------------------------

    def set_status(self, status: str) -> dict[str, Any]:
        manifest = self.load_manifest()
        manifest["status"] = status
        manifest["updated_at"] = _now()
        self.manifest_path.write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
        )
        return manifest

    def verify_mission(self) -> dict[str, Any]:
        """Re-hash every registered artifact against the mission manifest."""
        manifest = self.load_manifest()
        results: list[dict[str, Any]] = []
        ok = True
        for name, expected_hash in sorted(manifest.get("artifacts", {}).items()):
            path = self.root / name
            if not path.exists():
                results.append({"artifact": name, "status": "MISSING"})
                ok = False
                continue
            actual = _sha256_file(path)
            status = "PINNED" if actual == expected_hash else "MUTATED"
            if status != "PINNED":
                ok = False
            results.append(
                {"artifact": name, "status": status, "sha256": actual}
            )
        return {"mission_id": self.mission_id, "ok": ok, "artifacts": results}


def _now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


