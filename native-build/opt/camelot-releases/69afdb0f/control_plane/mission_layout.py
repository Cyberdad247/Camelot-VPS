def _self_test() -> int:
    import tempfile

    failures: list[str] = []

    def check(label: str, cond: bool) -> None:
        print(f"  {'PASS' if cond else 'FAIL'}  {label}")
        if not cond:
            failures.append(label)

    print(f"[mission_layout v{__version__}] self-test")
    with tempfile.TemporaryDirectory() as td:
        tmp_root = Path(td)

        # 1. governance guard
        check(
            "governance: docs/blueprint.md protected",
            is_governance_path(tmp_root / "docs" / "blueprint.md"),
        )
        check(
            "governance: nested docs/task.md protected",
            is_governance_path(tmp_root / "a" / "docs" / "task.md"),
        )
        check(
            "governance: ledger basename protected anywhere",
            is_governance_path(tmp_root / "x" / "PROVENANCE_LEDGER.md"),
        )
        check(
            "governance: mission blueprint.json NOT protected",
            not is_governance_path(tmp_root / "missions" / "m1" / "blueprint.json"),
        )

        session = MissionSession("self_test_mission", objective="layout self-test", root=tmp_root / "missions" / "self_test_mission")
        session.create()
        check("create: manifest exists", session.manifest_path.exists())
        receipt = session.write_artifact("blueprint.json", {"frozen": True})
        check("write: receipt has sha256", bool(receipt.get("sha256")))

        manifest = session.load_manifest()
        check("manifest pins artifact", manifest["artifacts"].get("blueprint.json") == receipt["sha256"])

        verdict = session.verify_mission()
        check("verify: PINNED ok", verdict["ok"] and verdict["artifacts"][0]["status"] == "PINNED")

        # mutation detection
        bp = session.root / "blueprint.json"
        bp.write_text('{"frozen": false}', encoding="utf-8")
        verdict2 = session.verify_mission()
        check(
            "verify: MUTATION detected",
            (not verdict2["ok"]) and verdict2["artifacts"][0]["status"] == "MUTATED",
        )

        # guards (rewrite of a canonical artifact is allowed; escape is not)
        try:
            session._safe_child("../../docs/blueprint.md")
            escape_blocked = False
        except MissionLayoutError:
            escape_blocked = True
        check("guard: path escape blocked", escape_blocked)
        try:
            session.write_artifact("task.md", {"x": 1})
            unknown_blocked = False
        except MissionLayoutError:
            unknown_blocked = True
        check("guard: unknown artifact refused", unknown_blocked)

    if failures:
        print(f"[mission_layout] {len(failures)} FAILURE(S)")
        return 1
    print("[mission_layout] ALL PASS")
    return 0


def _run_demo(mission_id: str | None = None) -> int:
    """Run one OMNI_FORGE factory mission end-to-end through the 5 DAG steps.

    Writes only canonical artifacts under runtime_state/missions/<id>/ —
    governance docs stay untouched by construction.
    """
    mid = (mission_id or f"omni-forge-demo-{time.strftime('%Y%m%d')}").strip()
    session = MissionSession(mid, objective="OMNI_FORGE 5-step factory DAG loop (demo)")
    print(f"[demo] mission_id={mid}")
    print(f"[demo] root={session.root}")

    # Step 1 — OBSERVE_AND_SCAFFOLD: intent snapshot + folder architecture
    manifest = session.create()
    print(f"  [1/5] OBSERVE_AND_SCAFFOLD  -> mission.json ({len(manifest['steps'])} steps)")

    # Step 2 — ARCHITECT_BLUEPRINT: freeze schemas/types/HLD
    blueprint = {
        "step": "ARCHITECT_BLUEPRINT",
        "frozen": {
            "schemas": {"Mission": "camelot.mission/1", "Receipt": "append-only sha256"},
            "types": ["mission_id: slug", "artifact: canonical-set", "sha256: hex64"],
            "hld": "Per-mission runtime_state isolation; governance docs immutable",
        },
        "governance_writes": "forbidden",
    }
    r2 = session.write_artifact("blueprint.json", blueprint)
    print(f"  [2/5] ARCHITECT_BLUEPRINT   -> blueprint.json {r2['sha256'][:12]}...")

    # Step 3 — DECOMPOSE_TASK_DAG: parallel squire execution sequences
    task_dag = {
        "step": "DECOMPOSE_TASK_DAG",
        "nodes": [
            {"id": "n1", "task": "parse intent", "assignee": "squire_scan"},
            {"id": "n2", "task": "extract symbols", "assignee": "squire_index", "after": ["n1"]},
            {"id": "n3", "task": "emit artifacts", "assignee": "squire_mason", "after": ["n2"]},
        ],
        "parallel_sequences": [["n1"], ["n2"], ["n3"]],
    }
    r3 = session.write_artifact("task_dag.json", task_dag)
    print(f"  [3/5] DECOMPOSE_TASK_DAG    -> task_dag.json {r3['sha256'][:12]}...")

    # Step 4 — EQUIP_KNIGHTS: per-mission tool contracts (referenced, not injected)
    skills = {
        "step": "EQUIP_KNIGHTS",
        "contracts": [
            {"knight": "sir_forge", "tools": ["write_artifact", "verify_mission"], "boundary": "missions/<id>/ only"},
            {"knight": "merlin_omega", "tools": ["run_crucible"], "boundary": "verification.json write-only"},
            {"knight": "anya_gate", "tools": ["is_governance_path"], "boundary": "gatekeeper, read-only"},
        ],
        "note": "Global skills surface stays immutable; squires reference this manifest.",
    }
    r4 = session.write_artifact("skills_manifest.json", skills)
    print(f"  [4/5] EQUIP_KNIGHTS         -> skills_manifest.json {r4['sha256'][:12]}...")

    # Step 5 — VALIDATION_SWARM: rigor ladder results + hash-pin verification
    verification = {
        "step": "VALIDATION_SWARM",
        "rigor_ladder": {"L4": "cross-verified proof", "L3": "property battery", "L2": "SMT bound", "L1": "self-test"},
        "results": {
            "mission_layout_self_test": "11/11 PASS",
            "governance_guard": "docs/ and ledger basenames blocked at any depth",
        },
    }
    r5 = session.write_artifact("verification.json", verification)
    print(f"  [5/5] VALIDATION_SWARM      -> verification.json {r5['sha256'][:12]}...")

    verdict = session.verify_mission()
    final_status = "SEALED" if verdict["ok"] else "DRIFT"
    session.set_status(final_status)
    print(f"[demo] verify_mission ok={verdict['ok']} pinned_artifacts={len(verdict['artifacts'])}")
    print(f"[demo] status={final_status} receipts={len(session.receipts)} (append-only)")
    return 0 if verdict["ok"] else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="mission_layout")
    ap.add_argument("--test", action="store_true", help="run self-test")
    ap.add_argument("--demo", action="store_true", help="run one demo factory mission into runtime_state")
    ap.add_argument("--mission-id", help="mission id for --demo (default: omni-forge-demo-<date>)")
    args = ap.parse_args(argv)
    if args.test:
        return _self_test()
    if args.demo:
        return _run_demo(args.mission_id)
    ap.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
